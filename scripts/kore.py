def git_toplevel(path):
    try:
        r = subprocess.run(["git", "-C", path, "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    except OSError:
        return None
    return os.path.abspath(r.stdout.strip()) if r.returncode == 0 and r.stdout.strip() else None


def kore_cmd(root):
    """How the bot folder's CLAUDE.md calls this script. The skill may be installed per user
    (~/.claude/skills) or inside the repo (<repo>/.claude/skills): use a path that works for everyone."""
    me = os.path.join(HERE, "kore.py")
    repo = git_toplevel(root) or root
    if os.path.normcase(me).startswith(os.path.normcase(repo) + os.sep):  # skill committed in the same repo
        return f'python "{os.path.relpath(me, root).replace(os.sep, "/")}"'
    return 'python "$HOME/.claude/skills/kore-xo-dialogs/scripts/kore.py"'


def merge_lines(path, lines):
    have = open(path, encoding="utf-8").read().splitlines() if os.path.isfile(path) else []
    add = [x for x in lines if x not in have]
    if add:
        write_text(path, "\n".join(have + add) + "\n")


def init_project(root):
    """CLAUDE.md, the hook + deny rules that keep the agent out of env/ and the built zips, ignore files.
    Existing files (a repo's own CLAUDE.md, .gitignore, settings) are merged, never replaced."""
    protected = (ENVDIR, f"{WS}/{PACKAGE}")
    # Claude Code reads .claude/settings.json of the folder it is started in: the bot folder, or the repo root
    # when the bot lives in a subfolder of a repo (e.g. next to a project-level skill). Protect both.
    for croot in dict.fromkeys([root, git_toplevel(root) or root]):
        os.makedirs(os.path.join(croot, ".claude", "hooks"), exist_ok=True)
        shutil.copy2(os.path.join(HERE, "..", "project", "vault_guard.py"),
                     os.path.join(croot, ".claude", "hooks", "vault_guard.py"))
        sp = os.path.join(croot, ".claude", "settings.json")
