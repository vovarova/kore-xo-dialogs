#!/usr/bin/env python3
"""kore - pipeline around kxo for ONE Kore.ai XO bot per project folder.

  1. IMPORT   kore import <export.zip|folder> --env <name> [--to <folder>]
              anonymised workspace + AI-friendly views; env values/credentials -> env/<name>.json
  2. DEVELOP  kore kxo <kxo command ...>   edit dialogs (views regenerate afterwards)
  3. BUILD    kore build --env <name>      workspace + env/<name>.json -> workspace/import-package/<Bot>-<name>.zip

Project layout:
  README.md, dialogs/<Dialog>/{flow.md,spec.json}, env.md, tools.md, components.md, index.json   generated views
  specs/                      your draft specs
  workspace/                  anonymised kxo workspace
  env/<name>.json             values per environment (uat, prod, ...): git-ignored, blocked for the agent
  workspace/import-package/   built zips with real values: git-ignored, blocked for the agent

Python 3.8+, standard library only.
"""
