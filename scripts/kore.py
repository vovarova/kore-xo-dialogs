TOKEN_RE = re.compile(r"__KXO(?:ENV|SEC)_[A-Za-z0-9_]+?__(?:[UI]__)?")
# field names whose string value is a credential (matched against JSON keys in appDefinition.json)
SECRET_KEY_RE = re.compile(r"(secret|password|passwd|api_?key|apikey|access_?token|refresh_?token|"
                           r"private_?key|bearer|signing_?key|^token$|^client_?id$|jwt)", re.I)
SECRET_KEY_SKIP_RE = re.compile(r"(url|uri|enabled|type|required|name|label|desc)$", re.I)
SECRET_HEADER_RE = re.compile(r"(authorization|api[-_]?key|token|secret|password|cookie)", re.I)


# --------------------------------------------------------------------------- project
def find_root(a, required=True):
    if getattr(a, "root", None):
        return os.path.abspath(a.root)
    d = os.getcwd()
    while True:
        if os.path.isfile(os.path.join(d, MARKER)):
            return d
        up = os.path.dirname(d)
        if up == d:
            if required:
                raise KxoError(f"no {MARKER} found from {os.getcwd()} upwards; use `kore import <export> --to <folder>`")
            return None
        d = up


def safe_name(s):
    return re.sub(r"[^A-Za-z0-9._-]+", "_", s or "").strip("_.") or "bot"


class Project:
    """One project folder = one Kore bot."""

    def __init__(self, root):
        self.root = os.path.abspath(root)
        self.ws = os.path.join(self.root, WS)
        self.envdir = os.path.join(self.root, ENVDIR)
        self.meta_path = os.path.join(self.root, MARKER)

    @property
    def meta(self):
        return load_json(self.meta_path) if os.path.isfile(self.meta_path) else {}

    def save_meta(self, m):
        save_json(self.meta_path, m, indent=2)

    def env_path(self, name):
        if not re.match(r"^[A-Za-z0-9_-]+$", name or ""):
            raise KxoError(f"bad env name '{name}' (letters, digits, - and _)")
        return os.path.join(self.envdir, f"{name}.json")

    def envs(self):
        return sorted(f[:-5] for f in os.listdir(self.envdir) if f.endswith(".json")) if os.path.isdir(self.envdir) else []

    def load_env(self, name):
        p = self.env_path(name)
        if not os.path.isfile(p):
            raise KxoError(f"no env '{name}' ({p}). Existing: {', '.join(self.envs()) or 'none'}. Create it by "
                           "copying another env file, or `kore import <export> --env <name>`.")
        return load_json(p)


def get_project(a):
    prj = Project(find_root(a))
    if not os.path.isfile(os.path.join(prj.ws, kxo.APPDEF)):
        raise KxoError(f"{prj.ws} has no {kxo.APPDEF}; run `kore import <export> --env <name>` first")
    return prj


def env_tokens(env):
    """token -> value from an env file."""
    t = {env_token(k): v for k, v in (env.get("env") or {}).items() if isinstance(v, str) and v != ""}
    t.update({k: v for k, v in (env.get("secrets") or {}).items() if isinstance(v, str) and v != ""})
    return t


# --------------------------------------------------------------------------- export reading
def read_export(src):
    """-> {filename: bytes} of the single bot export in a zip or folder."""
    found = []
    if os.path.isdir(src):
        for dp, _, fs in os.walk(src):
            if "appDefinition.json" in fs:
                found.append({f: open(os.path.join(dp, f), "rb").read() for f in EXPORT_FILES if f in fs})
    elif zipfile.is_zipfile(src):
        z = zipfile.ZipFile(src)
        groups = {}
        for m in z.namelist():
            if os.path.basename(m) in EXPORT_FILES:
                groups.setdefault(os.path.dirname(m), {})[os.path.basename(m)] = z.read(m)
        found = [g for g in groups.values() if "appDefinition.json" in g]
    else:
        raise KxoError(f"{src} is neither a folder nor a zip")
    if len(found) != 1:
        raise KxoError(f"{src} must contain exactly one bot export (appDefinition.json); found {len(found)}")
    return found[0]


# --------------------------------------------------------------------------- anonymisation
def env_token(key):
    return f"__KXOENV_{re.sub(r'[^A-Za-z0-9_]', '_', key)}__"


def variants(token, value):
    """(text form in export, token form) pairs: raw, encodeURIComponent, encodeURI."""
    v = [(value, token)]
    e = enc(value)
    if e != value:
        v.append((e, token + "U__"))
    u = enc_uri(value)
    if u != value and u != e:
        v.append((u, token + "I__"))
    return v


def restore_map(tokens):
    m = {}
    for tok, val in tokens.items():
        for text, t in variants(tok, val):
            m[t] = text
    return m


def globally_replaceable(v):
    """Only distinctive values are replaced wherever they appear (short/plain words would hit normal text)."""
    return isinstance(v, str) and len(v) >= 8 and re.search(r"[^A-Za-z ]", v) and not v.isdigit() \
        and v.lower() not in ("true", "false", "null", "undefined")


def sub_strings(obj, rx, fn):
    """Apply rx.sub(fn) to every string value (not keys) in a JSON tree, in place. Returns count."""
    n = [0]

    def walk(o):
        items = o.items() if isinstance(o, dict) else enumerate(o) if isinstance(o, list) else ()
        for k, v in list(items):
            if isinstance(v, str):
                nv = rx.sub(fn, v)
                if nv != v:
                    o[k] = nv
                    n[0] += 1
            else:
                walk(v)
    walk(obj)
    return n[0]


def multi_rx(strings):
    strings = sorted(set(s for s in strings if s), key=len, reverse=True)
    return re.compile("|".join(re.escape(s) for s in strings)) if strings else None


def is_template(v):
    return "{{" in v or "env." in v or "context." in v or TOKEN_RE.search(v)


def anonymise(appdef, config, botfn, known):
    """Replace env values and credentials with tokens. `known` = token->value from the env file (stable names).
    Returns (appdef, config, botfn, tokens{token: {value, source}}, report lines)."""
    for name, obj in (("appDefinition.json", appdef), ("config.json", config)):
        if TOKEN_RE.search(json.dumps(obj)):
            raise KxoError(f"{name} already contains __KXO tokens; was it built without restoring secrets?")
    appdef, config = copy.deepcopy(appdef), copy.deepcopy(config)
    tokens, by_value, report = {}, {}, []
    for tok, val in known.items():
        by_value.setdefault(val, tok)

    def register(tok, value, source):
        if value in by_value and by_value[value] in tokens:
            return by_value[value]
        tokens[tok] = {"value": value, "source": source}
        by_value[value] = tok
        return tok

    for ev in config.get("envVariables") or []:  # 1. env variables (config.json)
        v, key = ev.get("value"), ev.get("key", "")
        if isinstance(v, str) and v != "":
            tok = env_token(key)
            tokens[tok] = {"value": v, "source": f"env {key}"}
            by_value.setdefault(v, tok)
            ev["value"] = tok
    counter = [0]
    found = {}

    def walk(o, path):  # 2. credential fields in appDefinition.json
        if isinstance(o, dict):
            for k, v in o.items():
                p = f"{path}.{k}"
                if isinstance(v, str) and v and SECRET_KEY_RE.search(k) and not SECRET_KEY_SKIP_RE.search(k) \
                        and not is_template(v):
                    existing = by_value.get(v)
                    if existing in tokens:
                        tok = existing
                    else:
                        counter[0] += 1
                        tok = existing if existing else f"__KXOSEC_{re.sub(r'[^A-Za-z0-9]', '', k)}_{counter[0]}__"
                        tok = register(tok, v, re.sub(r"\[\d+\]", "[]", p))
                    o[k] = tok
                    g = re.sub(r"\[\d+\]", "[]", p)
                    found[g] = found.get(g, 0) + 1
                elif k == "headers" and isinstance(v, dict) and isinstance(v.get("value"), str):
                    try:
                        h = json.loads(v["value"] or "{}")
                    except ValueError:
                        h = {}
                    for hk, hv in (h.items() if isinstance(h, dict) else []):
                        if isinstance(hv, str) and SECRET_HEADER_RE.search(hk) and len(hv) >= 8 and not is_template(hv):
                            counter[0] += 1
                            register(f"__KXOSEC_header_{re.sub(r'[^A-Za-z0-9]', '', hk)}_{counter[0]}__", hv,
                                     f"service header {hk}")
                    walk(v, p)
                else:
                    walk(v, p)
        elif isinstance(o, list):
            for i, v in enumerate(o):
                walk(v, f"{path}[{i}]")
    walk(appdef, "")
    for g, n in sorted(found.items()):
        report.append(f"credential field x{n}: {g}")
    pairs = {}  # 3. other literal copies of distinctive values (raw / URL-encoded)
    not_secret = {appdef.get("_id"), appdef.get("refId")}
    for tok, t in tokens.items():
        if globally_replaceable(t["value"]) and t["value"] not in not_secret:
            for text, tt in variants(tok, t["value"]):
                pairs[text] = tt
    rx = multi_rx(pairs)
    if rx:
        n = sub_strings(appdef, rx, lambda m: pairs[m.group(0)]) + sub_strings(config, rx, lambda m: pairs[m.group(0)])
        if botfn is not None:
            botfn, k = rx.subn(lambda m: pairs[m.group(0)], botfn)
            n += k
        if n:
            report.append(f"hard-coded copies of values replaced in {n} string(s)")
    return appdef, config, botfn, tokens, report


def restore(obj, tokens):
    m = restore_map(tokens)
    rx = multi_rx(m)
    if rx:
        sub_strings(obj, rx, lambda x: m[x.group(0)])
    return obj


def restore_text(s, tokens):
    m = restore_map(tokens)
    rx = multi_rx(m)
    return rx.sub(lambda x: m[x.group(0)], s) if rx else s


def leftover_tokens(obj):
    return sorted(set(TOKEN_RE.findall(obj if isinstance(obj, str) else json.dumps(obj, ensure_ascii=False))))


# --------------------------------------------------------------------------- views
def slug(s):
    return re.sub(r"[^A-Za-z0-9._ -]+", "_", s).strip(" ._") or "dialog"


def mermaid(spec):
    ids = {}

    def nid(x):
        if x not in ids:
            ids[x] = f"n{len(ids)}"
        return ids[x]
    lines = ["flowchart TD", f'  {nid("__intent")}(["intent: {mq(spec["intent"].get("name") or "")}"])']
    for n in spec["nodes"]:
        lines.append(f'  {nid(n.get("name") or n["id"])}["{mq(n.get("name") or n["id"])}<br/><i>{n["type"]}</i>"]')
    if spec.get("start"):
        lines.append(f'  {nid("__intent")} --> {nid(spec["start"])}')
    for n in spec["nodes"]:
        src = nid(n.get("name") or n["id"])
        if n.get("next") not in (None, ""):
            lines.append(f"  {src} --> {nid(n['next'])}")
        for t in n.get("transitions", []):
            tgt = t.get("default", t.get("to"))
            if tgt in (None, ""):
                continue
            lbl = "else" if "default" in t else cond_label(t.get("if"))
            lines.append(f'  {src} -->|"{mq(lbl)}"| {nid(tgt)}')
    for special in ("end", "retToFlow"):
        if special in ids:
            lines.append(f'  {ids[special]}(("{special}"))')
    return "\n".join(lines)


def cond_label(c):
    if not isinstance(c, dict):
        return "if"
    if "tests" in c:
        return f" {c.get('conjoin', 'and')} ".join(cond_label(t) for t in c["tests"])
    if "dialogAct" in c:
        return c["dialogAct"]
    return f"{c.get('context') or c.get('field') or c.get('entity') or '?'} {c.get('op', '')} {c.get('value', '')}"[:60]


def mq(s):
    return str(s).replace('"', "'").replace("\n", " ")[:80]


def flow_md(app, dlg, spec, rel):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        kxo.show(app, dlg)
    return (f"# {spec['dialog']}\n\n"
            f"Generated - do not edit. Edit `spec.json` next to this file, then `kore kxo apply \"{rel}/spec.json\"`.\n\n"
            f"- refId: `{spec['refId']}`\n- hidden: {spec['hidden']}\n"
            f"- description: {spec['description'] or '-'}\n"
            f"- utterances: {', '.join(spec['intent']['utterances']) or '-'}\n\n"
            f"```mermaid\n{mermaid(spec)}\n```\n\n## Nodes\n\n```\n{buf.getvalue()}```\n")


def write_text(p, s):
    try:
        with open(p, encoding="utf-8", newline="") as f:
            if f.read() == s:
                return  # unchanged: don't touch
    except OSError:
        pass
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)


def prune(top, keep):
    """Remove files under `top` not in `keep` (no rmtree: Windows editors/indexers lock folders)."""
    for dp, _, fns in os.walk(top, topdown=False):
        for fn in fns:
            p = os.path.join(dp, fn)
            if os.path.normcase(os.path.abspath(p)) not in keep:
                try:
                    os.remove(p)
                except OSError:
                    pass
        if dp != top:
            try:
                os.rmdir(dp)
            except OSError:
                pass


def generate_views(prj):
    app = kxo.App(prj.ws)
    ddir = os.path.join(prj.root, "dialogs")
    os.makedirs(ddir, exist_ok=True)
    written, usage = set(), app.component_usage()
    rows, used_slugs, env_refs = [], set(), {}
    for dlg in sorted(app.d["dialogs"], key=lambda d: app.dname(d).lower()):
        name = app.dname(dlg)
        spec = kxo.dialog_to_spec(app, dlg)
        s = slug(name)
        if s.lower() in used_slugs:
            s = f"{s}__{dlg['refId'][:8]}"
        used_slugs.add(s.lower())
        hidden = bool(dlg.get("isHidden"))
        rel = f"dialogs/{'_hidden/' if hidden else ''}{s}"
        d = os.path.join(prj.root, rel)
        os.makedirs(d, exist_ok=True)
        for fn, body in (("spec.json", json.dumps(spec, indent=2, ensure_ascii=False) + "\n"),
                         ("flow.md", flow_md(app, dlg, spec, rel))):
            p = os.path.join(d, fn)
            write_text(p, body)
            written.add(os.path.normcase(os.path.abspath(p)))
        for k in set(re.findall(r"env\.([A-Za-z0-9_]+)", json.dumps(spec))):
            env_refs.setdefault(k, set()).add(name)
        rows.append((name, hidden, rel, spec))
    prune(ddir, written)
    cfg = load_json(os.path.join(prj.ws, kxo.CONFIG)) if os.path.isfile(os.path.join(prj.ws, kxo.CONFIG)) else {}
    envs = {n: prj.load_env(n) for n in prj.envs()}
    el = ["# Environment variables\n",
          "Values are NOT here: they are in `env/<name>.json` (never open those files) and are combined only by "
          "`kore build --env <name>`. Reference them in dialogs as `{{env.KEY}}` (messages/urls) or `env.KEY` "
          "(scripts). Placeholders like `__KXOENV_KEY__` stand for the value of the env being built; never invent "
          "new ones.\n",
          "| key | placeholder | " + " | ".join(envs) + " | used in |", "|---|---|" + "---|" * len(envs) + "---|"]
    for ev in cfg.get("envVariables") or []:
        k = ev.get("key", "")
        st = ["set" if (e.get("env") or {}).get(k) else "**EMPTY**" for e in envs.values()]
        el.append(f"| {k} | `{env_token(k)}` | " + " | ".join(st) + f" | {', '.join(sorted(env_refs.get(k, []))) or '-'} |")
    sec = prj.meta.get("secretTokens") or {}
    if sec:
        el += ["\n## Credentials (also per env, under `secrets`)\n", "| placeholder | where |", "|---|---|"]
        el += [f"| `{t}` | {s} |" for t, s in sec.items()]
    write_text(os.path.join(prj.root, "env.md"), "\n".join(el) + "\n")
    tl = ["# App-level agent tools\n"]
    for t in app.d["tools"]:
        acts = [app.comp_by_ref.get(x.get("action_id"), {}).get("name", x.get("action_id"))
                for x in t.get("tool_actions") or []]
        tl.append(f"## {t.get('tool_name')}\n\n{t.get('tool_desc') or t.get('description') or ''}\n\n"
                  f"- respPath: `{t.get('resp_path')}`\n- params: "
                  f"{', '.join(p.get('name', '?') + ' (' + str(p.get('type')) + ')' for p in t.get('params') or []) or '-'}"
                  f"\n- actions: {', '.join(acts) or '-'}\n")
    if not app.d["tools"]:
        tl.append("(none)")
    write_text(os.path.join(prj.root, "tools.md"), "\n".join(tl) + "\n")
    cl = ["# Components (nodes) and the dialogs using them\n",
          "Shared components (used by >1 dialog) change every dialog when edited.\n",
          "| component | type | dialogs |", "|---|---|---|"]
    for c in sorted(app.d["dialogComponents"], key=lambda c: c.get("name", "").lower()):
        if c.get("type") == "intent":
            continue
        ds = sorted(usage.get(c["_id"], set()))
        cl.append(f"| {c.get('name')} | {kxo.FRIENDLY.get(c.get('type'), c.get('type'))} | "
                  f"{(', '.join(ds) if len(ds) < 8 else ', '.join(ds[:8]) + f' (+{len(ds) - 8})') or '(unused)'} |")
    write_text(os.path.join(prj.root, "components.md"), "\n".join(cl) + "\n")
    idx = [{"dialog": n, "hidden": h, "path": r, "refId": s["refId"], "start": s.get("start"),
            "nodes": len(s["nodes"]), "utterances": len(s["intent"]["utterances"]),
            "nodeTypes": sorted({x["type"] for x in s["nodes"]})} for n, h, r, s in rows]
    write_text(os.path.join(prj.root, "index.json"),
               json.dumps({"bot": prj.meta.get("name"), "dialogs": idx}, indent=2, ensure_ascii=False) + "\n")
    m = prj.meta
    r = [f"# {m.get('name', os.path.basename(prj.root))}\n",
         f"Kore app `{m.get('appId')}` · language `{app.lang}` · platform {m.get('koreVersion')} · "
         f"imported {m.get('importedAt')} from `{m.get('source')}`\n",
         "Generated by `kore` - do not edit. Rules for working here: `CLAUDE.md`.\n",
         "## Where things are\n", "| path | what |", "|---|---|",
         "| `dialogs/<Dialog>/flow.md` | readable flow + mermaid diagram |",
         "| `dialogs/<Dialog>/spec.json` | editable kxo spec; `kore kxo apply <path>` |",
         "| `dialogs/_hidden/` | hidden / system dialogs |",
         "| `specs/` | your draft specs (new dialogs, partial edits) |",
         "| `components.md` | every node -> dialogs using it (check before editing shared nodes) |",
         "| `env.md` | env variable keys, placeholders, which envs have values (no values) |",
         "| `tools.md` | app-level agent tools |",
         "| `workspace/` | anonymised kxo workspace; never edit by hand |\n",
         f"## Dialogs ({sum(1 for x in rows if not x[1])} visible, {sum(1 for x in rows if x[1])} hidden)\n",
         "| dialog | nodes | utterances | node types |", "|---|---|---|---|"]
    for n, h, rel, s in rows:
        if not h:
            r.append(f"| [{n}](<{rel}/flow.md>) | {len(s['nodes'])} | {len(s['intent']['utterances'])} | "
                     f"{', '.join(sorted({x['type'] for x in s['nodes']}))} |")
    hid = [n for n, h, _, _ in rows if h]
    if hid:
        r.append(f"\nHidden: {', '.join(hid)}")
    write_text(os.path.join(prj.root, "README.md"), "\n".join(r) + "\n")
    os.makedirs(os.path.join(prj.root, "specs"), exist_ok=True)
    return len(rows)


