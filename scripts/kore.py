def cmd_import(a):
    root = os.path.abspath(a.to) if a.to else find_root(a, required=False)
    if not root:
        raise KxoError("not inside a kore project: use `kore import <export> --env <name> --to <new folder>`")
    prj = Project(root)
    files = read_export(a.export)
    appdef = json.loads(files["appDefinition.json"])
    config = json.loads(files.get("config.json") or b"{}")
    botfn = files["botFunctions.js"].decode("utf-8") if "botFunctions.js" in files else None
    m = prj.meta
    if m.get("appId") and m["appId"] != appdef.get("_id"):
        raise KxoError(f"this folder holds bot {m.get('name')} ({m['appId']}); the export is another bot "
                       f"({appdef.get('_id')}). One folder per bot: use --to <another folder>.")
    os.makedirs(root, exist_ok=True)
    init_project(root)
    env_p = prj.env_path(a.env)
    old = load_json(env_p) if os.path.isfile(env_p) else {}
    known = env_tokens(old)
    ap2, cf2, bf2, tokens, report = anonymise(appdef, config, botfn, known)
    tk = {k: v["value"] for k, v in tokens.items()}
    if restore(copy.deepcopy(ap2), tk) != appdef or restore(copy.deepcopy(cf2), tk) != config or \
            (botfn is not None and restore_text(bf2, tk) != botfn):
        raise KxoError("anonymisation is not reversible for this export; nothing written. Please report.")
    os.makedirs(prj.ws, exist_ok=True)
    save_json(os.path.join(prj.ws, kxo.APPDEF), ap2)
    save_json(os.path.join(prj.ws, kxo.CONFIG), cf2)
    if "icon.png" in files:
        open(os.path.join(prj.ws, "icon.png"), "wb").write(files["icon.png"])
    if bf2 is not None:
        write_text(os.path.join(prj.ws, "botFunctions.js"), bf2)
    # env/<name>.json: exported values; a value the export leaves empty (Kore exports secured vars empty) keeps
    # what the file already had
    old_env, old_sec = old.get("env") or {}, old.get("secrets") or {}
    env_vals = {}
    for ev in config.get("envVariables") or []:
        k = ev.get("key", "")
        env_vals[k] = ev.get("value") or old_env.get(k, "")
    secrets = {t: v["value"] for t, v in tokens.items() if t.startswith("__KXOSEC")}
    for t, v in old_sec.items():
        secrets.setdefault(t, v)
    os.makedirs(prj.envdir, exist_ok=True)
    save_json(env_p, {"env": env_vals, "secrets": secrets}, indent=2)
    m.update({"name": (json.loads(files["config.json"]).get("name") if "config.json" in files else None)
              or appdef.get("_id"),
              "appId": appdef.get("_id"), "koreVersion": appdef.get("environmentVersionInfo"),
              "importedAt": dt.datetime.now().isoformat(timespec="seconds"),
              "source": os.path.basename(a.export),
              "secretTokens": {t: v["source"] for t, v in tokens.items() if t.startswith("__KXOSEC")}})
    prj.save_meta(m)
    n = generate_views(prj)
    info(f"{m['name']} -> {root}")
    for line in report:
        info("  " + line)
    empty = [k for k, v in env_vals.items() if not v]
    info(f"  env '{a.env}': {len(env_vals)} variables, {len(secrets)} credentials -> {env_p}")
    if empty:
        info(f"  EMPTY in env '{a.env}' (secured vars are exported empty): {', '.join(empty)}")
    info(f"  {n} dialogs -> {os.path.join(root, 'README.md')}")


# --------------------------------------------------------------------------- stage 2: develop (kxo passthrough)
def cmd_kxo(a):
    prj = get_project(a)
    args = list(a.args)
    if args and args[0] == "--":
        args = args[1:]
    if not args:
        raise KxoError("usage: kore kxo <kxo command> [args]   e.g. kore kxo apply specs/new.json")
    if args[0] in ("init", "deploy", "export-api", "build", "diff"):
        raise KxoError(f"kxo {args[0]} is not used here (use `kore import` / `kore build`; changes: `git diff`)")
    code = 0
    try:
        kxo.main([args[0], "-w", prj.ws] + args[1:])
    except SystemExit as e:
        code = e.code or 0
    if args[0] in ("apply", "clone", "delete-dialog") and "--dry-run" not in args and code == 0:
        generate_views(prj)
    if code:
        sys.exit(code)


# --------------------------------------------------------------------------- stage 3: build
def cmd_build(a):
    """workspace + env/<name>.json -> workspace/import-package/<Bot>-<name>.zip (hash removed)."""
    prj = get_project(a)
    env = prj.load_env(a.env)
    tokens = env_tokens(env)
    app = kxo.App(prj.ws)
    errs, _ = kxo.validate(app)
    if errs:
        raise KxoError("fix validation errors first (`kore kxo validate`): " + "; ".join(errs[:5]))
    ap = restore(copy.deepcopy(app.d), tokens)
    ap.pop("encryptedHash", None)
    ap.pop("latestEncryptedHash", None)
    cf = load_json(os.path.join(prj.ws, kxo.CONFIG))
    for ev in cf.get("envVariables") or []:
        ev["value"] = (env.get("env") or {}).get(ev.get("key"), "")
    restore(cf, tokens)
    entries = [(kxo.APPDEF, json.dumps(ap, indent=4, ensure_ascii=False)),
               (kxo.CONFIG, json.dumps(cf, indent=4, ensure_ascii=False))]
    if os.path.isfile(os.path.join(prj.ws, "botFunctions.js")):
        entries.append(("botFunctions.js", restore_text(open(os.path.join(prj.ws, "botFunctions.js"),
                                                             encoding="utf-8").read(), tokens)))
    left = sorted(set(t for _, text in entries for t in leftover_tokens(text)))
    if left:
        raise KxoError(f"env '{a.env}' has no value for: {', '.join(left)} (add it to env/{a.env}.json; "
                       "new placeholders must not be invented - use {{env.KEY}} / env.KEY)")
    pkg = os.path.join(prj.ws, PACKAGE)
    os.makedirs(pkg, exist_ok=True)
    zp = os.path.join(pkg, f"{safe_name(prj.meta.get('name'))}-{a.env}.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for name, text in entries:
            z.writestr(name, text.encode("utf-8"))
        if os.path.isfile(os.path.join(prj.ws, "icon.png")):
            z.write(os.path.join(prj.ws, "icon.png"), "icon.png")
    info(f"built {zp}")
    empty = [ev.get("key") for ev in cf.get("envVariables") or [] if not ev.get("value")]
    if empty:
        warn(f"empty in env '{a.env}': {', '.join(empty)}")


# --------------------------------------------------------------------------- cli
def main(argv=None):
    p = argparse.ArgumentParser(prog="kore", description=__doc__.split("\n\n")[0])
    p.add_argument("--root", help="project folder (default: folder with kore.project.json above cwd)")
    sp = p.add_subparsers(dest="cmd", required=True)
    s = sp.add_parser("import", help="import a Kore export into this project (or a new one with --to)")
    s.set_defaults(fn=cmd_import)
    s.add_argument("export")
    s.add_argument("--env", required=True, help="environment the export comes from (e.g. uat): values go to env/<env>.json")
    s.add_argument("--to", help="project folder to create/use (one folder per bot)")
    s = sp.add_parser("kxo", help="run a kxo command on the workspace (list/show/get/apply/clone/validate/diff)")
    s.set_defaults(fn=cmd_kxo)
    s.add_argument("args", nargs=argparse.REMAINDER)
    s = sp.add_parser("build", help="build the import zip for one environment")
    s.set_defaults(fn=cmd_build)
    s.add_argument("--env", required=True, help="environment to build for: values from env/<env>.json")
    a = p.parse_args(argv)
    try:
        a.fn(a)
    except KxoError as e:
        print("ERROR: " + str(e), file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main()
